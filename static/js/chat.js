function applyTheme(theme) {
    document.documentElement.setAttribute("data-theme", theme);

    localStorage.setItem("wijesinghe-theme", theme);

    themeIcon.innerHTML = theme === "dark" ? sunIcon : moonIcon;

    themeToggle.setAttribute(
        "aria-label",
        theme === "dark" ? "Switch to light theme" : "Switch to dark theme"
    );

    themeToggle.setAttribute(
        "title",
        theme === "dark" ? "Switch to light theme" : "Switch to dark theme"
    );
}

function initializeTheme() {
    const savedTheme = localStorage.getItem("wijesinghe-theme");

    applyTheme(savedTheme === "dark" ? "dark" : "light");
}

themeToggle.addEventListener("click", () => {
    const currentTheme = document.documentElement.getAttribute("data-theme");

    applyTheme(currentTheme === "dark" ? "light" : "dark");
});

/* ADD MESSAGE */

function addMessage(role, content) {
    const message = document.createElement("div");
    message.className = `message ${role}`;

    const bubble = document.createElement("div");
    bubble.className = "message-bubble";
    bubble.textContent = content;

    message.appendChild(bubble);
    chatMessages.appendChild(message);

    scrollToBottom();
}

/* SCROLL */

function scrollToBottom() {
    chatMessages.scrollTop = chatMessages.scrollHeight;

    document.getElementById("chatMain").scrollTop =
        document.getElementById("chatMain").scrollHeight;
}

/* TYPING */

function showTyping() {
    const typing = document.createElement("div");
    typing.className = "message assistant";
    typing.id = "typingIndicator";

    typing.innerHTML = `
        <div class="typing-indicator">
            <span></span>
            <span></span>
            <span></span>
        </div>
    `;

    chatMessages.appendChild(typing);
    scrollToBottom();
}

function removeTyping() {
    const typing = document.getElementById("typingIndicator");

    if (typing) {
        typing.remove();
    }
}

/* SEND MESSAGE */

async function sendMessage(text = null) {
    const message = text || messageInput.value.trim();

    if (!message) return;

    welcomeScreen.style.display = "none";
    document.body.classList.add("chat-active");

    addMessage("user", message);

    conversation.push({
        role: "user",
        content: message
    });

    messageInput.value = "";
    messageInput.style.height = "auto";

    sendButton.disabled = true;

    showTyping();

    try {
        const response = await fetch("/api/chat", {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({
                messages: conversation,
                language: currentLanguage
            })
        });

        const data = await response.json();

        removeTyping();

        if (!response.ok) {
            throw new Error(data.error || "Request failed");
        }

        const assistantReply = data.reply || data.response || data.message;

        if (!assistantReply) {
            throw new Error("No response received");
        }

        addMessage("assistant", assistantReply);

        conversation.push({
            role: "assistant",
            content: assistantReply
        });

    } catch (error) {
        removeTyping();

        const errorMessage = currentLanguage === "si"
            ? "සමාවන්න, දැනට ප්‍රතිචාර ලබාගැනීමේ ගැටලුවක් ඇතිවී තිබේ. නැවත උත්සාහ කරන්න."
            : currentLanguage === "ta"
            ? "மன்னிக்கவும், பதிலைப் பெறுவதில் சிக்கல் ஏற்பட்டுள்ளது. மீண்டும் முயற்சிக்கவும்."
            : "Sorry, something went wrong. Please try again.";

        addMessage("assistant", errorMessage);

        console.error("Chat error:", error);

    } finally {
        sendButton.disabled = false;
        messageInput.focus();
        scrollToBottom();
    }
}

/* HOME / RESET CHAT */

function goHome() {
    conversation = [];

    chatMessages.innerHTML = "";

    welcomeScreen.style.display = "";

    document.body.classList.remove("chat-active");

    messageInput.value = "";
    messageInput.style.height = "auto";

    chatMessages.scrollTop = 0;

    document.getElementById("chatMain").scrollTop = 0;

    messageInput.blur();
}

homeButton.addEventListener("click", goHome);

/* SEND BUTTON */

sendButton.addEventListener("click", () => {
    sendMessage();
});

/* ENTER KEY */

messageInput.addEventListener("keydown", (event) => {
    if (event.key === "Enter" && !event.shiftKey) {
        event.preventDefault();
        sendMessage();
    }
});

/* AUTO RESIZE */

messageInput.addEventListener("input", () => {
    messageInput.style.height = "auto";

    messageInput.style.height =
        Math.min(messageInput.scrollHeight, 150) + "px";
});

